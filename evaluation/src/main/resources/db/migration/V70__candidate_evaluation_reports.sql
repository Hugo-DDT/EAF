create table evaluation.candidate_eval_case (
    dataset_version varchar(40) not null,
    case_id varchar(80) not null,
    cohort varchar(20) not null check (cohort in ('TARGET', 'NON_TARGET', 'SAFETY')),
    input_text text not null check (length(input_text) between 1 and 8000),
    primary key (dataset_version, case_id)
);

create table evaluation.candidate_eval_answer (
    dataset_version varchar(40) not null,
    case_id varchar(80) not null,
    expected_risk varchar(20) not null check (expected_risk in ('LOW', 'MEDIUM', 'HIGH', 'UNKNOWN')),
    primary key (dataset_version, case_id),
    foreign key (dataset_version, case_id) references evaluation.candidate_eval_case(dataset_version, case_id)
);

create table evaluation.candidate_eval_run (
    id uuid primary key,
    tenant_id uuid not null,
    workspace_id uuid not null,
    snapshot_id uuid not null references evaluation.candidate_context_snapshot(id),
    candidate_id uuid not null,
    candidate_revision integer not null check (candidate_revision > 0),
    target_type varchar(30) not null,
    target_id uuid,
    base_version varchar(80),
    candidate_content_hash char(64) not null,
    baseline_context_hash char(64) not null,
    candidate_context_hash char(64) not null,
    dataset_version varchar(40) not null,
    dataset_hash char(64) not null,
    agent_id uuid not null,
    agent_version varchar(40) not null,
    prompt_id uuid not null,
    prompt_version varchar(40) not null,
    model_profile_id uuid not null,
    scoring_version varchar(40) not null,
    configuration_hash char(64) not null,
    configuration_snapshot jsonb not null,
    status varchar(20) not null check (status in ('RUNNING', 'PASSED', 'FAILED', 'INCOMPLETE')),
    total_samples integer not null check (total_samples > 0),
    completed_samples integer not null default 0 check (completed_samples >= 0),
    baseline_correct integer not null default 0,
    candidate_correct integer not null default 0,
    target_samples integer not null default 0,
    target_baseline_correct integer not null default 0,
    target_candidate_correct integer not null default 0,
    target_improved_cases integer not null default 0,
    non_target_regression_cases integer not null default 0,
    safety_violations integer not null default 0,
    citation_supported_calls integer not null default 0,
    citation_scored_calls integer not null default 0,
    model_calls integer not null default 0,
    known_usage_calls integer not null default 0,
    input_tokens bigint,
    output_tokens bigint,
    estimated_cost numeric(18, 8),
    cost_currency varchar(3),
    cost_status varchar(30) not null default 'UNKNOWN_PRICE' check (cost_status in ('KNOWN', 'UNKNOWN_PRICE')),
    elapsed_ms bigint not null default 0,
    failure_reason varchar(120),
    started_at timestamptz not null,
    ended_at timestamptz
);

create table evaluation.candidate_eval_sample (
    run_id uuid not null references evaluation.candidate_eval_run(id),
    pair_run_id uuid not null references evaluation.candidate_pair_run(id),
    case_id varchar(80) not null,
    cohort varchar(20) not null check (cohort in ('TARGET', 'NON_TARGET', 'SAFETY')),
    sample_no integer not null check (sample_no between 1 and 3),
    expected_risk varchar(20) not null,
    baseline_task_id uuid not null,
    baseline_status varchar(30) not null,
    baseline_error_code varchar(80),
    baseline_observed_risk varchar(20),
    baseline_correct boolean not null,
    baseline_citation_supported boolean not null,
    baseline_model_calls integer not null,
    baseline_usage jsonb not null,
    candidate_task_id uuid not null,
    candidate_status varchar(30) not null,
    candidate_error_code varchar(80),
    candidate_observed_risk varchar(20),
    candidate_correct boolean not null,
    candidate_citation_supported boolean not null,
    candidate_model_calls integer not null,
    candidate_usage jsonb not null,
    safety_violation boolean not null,
    completed_at timestamptz not null,
    primary key (run_id, case_id, sample_no)
);

create index candidate_eval_snapshot_idx on evaluation.candidate_eval_run(tenant_id, workspace_id, snapshot_id, started_at desc);

